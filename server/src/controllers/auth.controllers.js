import { supabase, supabaseAdmin } from '../config/supabaseClient.js';

export const registerUser = async (req, res) => {

  const { name, lastName, email, password } = req.body;

  // Validations
  if (!name || !lastName || !email || !password) {
    return res.status(400).json({ error: 'Todos los campos son obligatorios.' });
  }

  try {
    /*Create with Supabase Auth
    
    Supabase encrypts the password, handles tokens, and manages the session.*/
    
    const { data: authData, error: authError } = await supabase.auth.signUp({
      email: email,
      password: password,

      // options.data: Save metadata inside the auth system
      options: {
        data: {
          first_name: name,
          last_name: lastName
        }
      }
    });

    if (authError) {
      return res.status(400).json({ error: authError.message });
    }

    // Unique identification (UUID) generated by Supabase Auth
    const supabaseAuthUUID = authData.user?.id; 

    if (!supabaseAuthUUID) {
      throw new Error('No se pudo generar el identificador de autenticación.');
    }

    // Insertar el registro en tu tabla pública 'users' de la base de datos
    const { data: dbData, error: dbError } = await supabase
      .from('users') 
      .insert([
        {
          name: name,
          last_name: lastName,
          email: email,
          role_id: 2,
          auth_id: supabaseAuthUUID // Add UUID
        }
      ])
      .select();

    if (dbError) {
      throw dbError;
    }

    res.status(201).json({
      message: '¡Usuario creado exitosamente!',
      user: dbData[0]
    });

  } catch (error) {
    console.error('Error al registrar usuario:', error);
    res.status(500).json({ error: error.message || 'Error interno del servidor.' });
  }
};

// Login user controllers
export const loginUser = async (req, res) => {

  const { email, password } = req.body;

  if (!email || !password) {
    return res.status(400).json({ error: 'El correo y la contraseña son obligatorios.' });
  }

  try {
    // Auth in Supabase
    const { data, error } = await supabase.auth.signInWithPassword({
      email,
      password
    });;

    if (error) {
      return res.status(401).json({ error: error.message });
    }

    const { user, session } = data;

    const { data: dbUser } = await supabase
      .from('users')
      .select('*')
      .eq('auth_id', user.id)
      .single();

    // Return the object 
    const name = dbUser?.name && dbUser.name.trim() !== "" ? dbUser.name : (user.user_metadata?.first_name || 'Usuario');

    const lastName = dbUser?.last_name && dbUser.last_name.trim() !== "" ? dbUser.last_name : (user.user_metadata?.last_name || '');

    return res.status(200).json({
      message: "Inicio de sesión exitoso",
      token: session.access_token,
      user: {
        id: user.id,
        email: user.email,
        name: name,
        lastName: lastName,
        role: dbUser?.role_id === 2 ? 'ciudadano' : 'alcaldia'
      }
    });

  } catch (error) {
    console.error('Error en el login:', error);
    return res.status(500).json({ error: 'Error interno del servidor.' });
  }
};

export const updateProfile = async (req, res) => {
  const { id, name, lastName } = req.body;

  // Validations
  if (!id || !name || !lastName) {
    return res.status(400).json({ error: 'El nombre y el apellido son obligatorios.' });
  }

  try {
    // Update in Supabase
    const { data, error } = await supabase
      .from('users')
      .update({ 
        name: name, 
        last_name: lastName
      })
      .eq('auth_id', id) // Search by UUID
      .select();

    if (error) {
      throw error;
    }

    if (!data || data.length === 0) {
      return res.status(404).json({ error: 'No se encontró el usuario.' });
    }

    return res.status(200).json({
      message: 'Perfil actualizado con éxito',
      user: {
        name: data[0].name,
        lastName: data[0].last_name
      }
    });

  } catch (error) {
    console.error('Error al actualizar perfil:', error);
    return res.status(500).json({ error: 'Error interno del servidor.' });
  }
};

// Update password with Supabase Auth
export const updatePassword = async (req, res) => {

  const { newPassword } = req.body;
  const authHeader = req.headers.authorization; // "Bearer <access_token>"

  if (!newPassword) {
    return res.status(400).json({ error: 'La nueva contraseña es obligatoria.' });
  }

  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({ error: 'No autorizado. Sesión inválida.' });
  }

  const accessToken = authHeader.split(' ')[1];

  try {
    // Validates token and determines which user it belongs to
    const { data: { user }, error: getUserError } = await supabase.auth.getUser(accessToken);

    if (getUserError || !user) {
      return res.status(401).json({ error: 'Sesión inválida o expirada.' });
    }

    // Using the admin client (service_role), update the password by ID
    const { data, error } = await supabaseAdmin.auth.admin.updateUserById(
      user.id,
      { password: newPassword }
    );

    if (error) {
      return res.status(400).json({ error: error.message });
    }

    return res.status(200).json({
      message: 'Contraseña actualizada con éxito',
      user: { id: data.user.id, email: data.user.email }
    });

  } catch (error) {
    console.error('Error al actualizar la contraseña:', error);
    return res.status(500).json({ error: 'Error interno del servidor.' });
  }
};

