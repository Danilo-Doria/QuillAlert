// Delete account
export const deleteAccount = async (req, res) => {
  const authHeader = req.headers.authorization; // "Bearer <access_token>"

  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({ error: 'No autorizado. Sesión inválida.' });
  }

  const accessToken = authHeader.split(' ')[1];

  try {

    const { data: { user }, error: getUserError } = await supabase.auth.getUser(accessToken);

    if (getUserError || !user) {
      return res.status(401).json({ error: 'Sesión inválida o expirada.' });
    }

    // Delete the record from 'users' table
    const { error: dbError } = await supabase
      .from('users')
      .delete()
      .eq('auth_id', user.id);

    if (dbError) {
      throw dbError;
    }

    // Delete the user's Supabase Auth (service_role key)
    const { error: authDeleteError } = await supabaseAdmin.auth.admin.deleteUser(user.id);

    if (authDeleteError) {
      throw authDeleteError;
    }

    return res.status(200).json({ message: 'Cuenta eliminada con éxito' });

  } catch (error) {
    console.error('Error al eliminar la cuenta:', error);
    return res.status(500).json({ error: error.message || 'Error interno del servidor.' });
  }
};

export const getUserById = async (req, res) => {
  const { id } = req.params;

  try {
    const { data, error } = await supabase
      .from('users')
      .select('name, last_name')
      .eq('auth_id', id)
      .single();

    if (error || !data) {
      return res.status(404).json({ error: 'Usuario no encontrado.' });
    }

    return res.status(200).json(data);

  } catch (error) {
    console.error('Error al consultar usuario:', error);
    return res.status(500).json({ error: 'Error interno del servidor.' });
  }
};